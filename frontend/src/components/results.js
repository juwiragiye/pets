export function renderResults(data) {
    const container = document.querySelector(
        '#results-content'
    );
    container.setAttribute('aria-busy', 'false');
    container.className = 'mt-6';
    

    container.innerHTML = `
        <div class="rounded-xl bg-brand-50 p-6">

            <p class="text-xs font-semibold uppercase
                      tracking-wider text-brand-600">
                Most likely breed
            </p>

            <h3 id="result-breed"
                class="mt-3 text-3xl font-bold
                       text-brand-900"></h3>

            <p id="result-confidence"
               class="mt-4 text-4xl font-bold
                      text-brand-600"></p>

            <p class="mt-1 text-sm text-slate-500">
                Model confidence
            </p>

        </div>

        <h4 class="mb-4 mt-8 font-semibold text-slate-700">
            Top predictions
        </h4>

        <div id="prediction-list" class="space-y-5"></div>

        <p class="mt-8 text-xs leading-relaxed text-slate-400">
            Predictions are estimates generated by a deep
            learning model and may not always be accurate.
        </p>
    `;

    document.querySelector('#result-breed')
        .textContent = data.breed;

    document.querySelector('#result-confidence')
        .textContent = `${(data.confidence * 100).toFixed(2)}%`;

    const list = document.querySelector('#prediction-list');

    data.predictions.forEach((prediction) => {
        const percentage = prediction.confidence * 100;

        const item = document.createElement('div');

        item.innerHTML = `
            <div class="mb-2 flex justify-between gap-3">
                <span class="breed-name text-sm
                             font-medium text-slate-700"></span>

                <span class="breed-confidence text-sm
                             text-slate-500"></span>
            </div>

            <div class="h-2 overflow-hidden rounded-full
                        bg-brand-100">

                <div class="confidence-bar h-full
                            rounded-full bg-brand-500
                            transition-all duration-500"></div>

            </div>
        `;

        item.querySelector('.breed-name')
            .textContent = prediction.breed;

        item.querySelector('.breed-confidence')
            .textContent = `${percentage.toFixed(2)}%`;

        item.querySelector('.confidence-bar')
            .style.width = `${percentage}%`;

        list.appendChild(item);
    });
}


